CREATE TABLE public.employee_schedule
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    employee_id   BIGINT NOT NULL,

    schedule_date DATE   NOT NULL,

    start_time    TIME   NOT NULL,

    end_time      TIME   NOT NULL,

    CONSTRAINT fk_employee_schedule_user
        FOREIGN KEY (employee_id)
            REFERENCES public.users (id),

    CONSTRAINT chk_employee_schedule_times
        CHECK (start_time < end_time)
);

CREATE INDEX idx_employee_schedule_employee_date
    ON public.employee_schedule (employee_id, schedule_date);
